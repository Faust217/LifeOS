package exporting

import (
	"crypto/rand"
	"fmt"
)

// Each synthetic command is a distinct user intent unless a test explicitly retains a key.
func newFinancialWriteKey() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(err)
	}
	b[6] = (b[6] & 15) | 64
	b[8] = (b[8] & 63) | 128
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[:4], b[4:6], b[6:8], b[8:10], b[10:])
}
